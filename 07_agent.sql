USE ROLE SYSADMIN;
USE WAREHOUSE AI_LAB_WH;
USE SCHEMA AI_LAB.SEMANTIC;

CREATE OR REPLACE AGENT AI_LAB.SEMANTIC.SALES_AGENT
  COMMENT = 'Sales, inventory and policy assistant over the governed Gold layer'
  PROFILE = '{"display_name": "Sales & Policy Assistant"}'
  FROM SPECIFICATION
  $$
  models:
    orchestration: auto
  instructions:
    response: "Answer concisely. State the metric definition used (for example: revenue means net revenue after discount). Format currency with thousands separators. If data is missing because of access rules, say the answer is limited to the user's permitted region."
    orchestration: "Use SalesAnalyst for any question about numbers: orders, revenue, customers, parts, suppliers, inventory, deliveries. Use PolicySearch for questions about definitions, policies, thresholds, SLAs or governance rules. For questions that need both (for example, which orders breach the late-delivery SLA), use PolicySearch first for the rule, then SalesAnalyst for the numbers."
  tools:
    - tool_spec:
        type: "cortex_analyst_text_to_sql"
        name: "SalesAnalyst"
        description: "Answers quantitative questions about orders, revenue, customers, parts, suppliers, inventory and late deliveries from the governed Gold star schema."
    - tool_spec:
        type: "cortex_search"
        name: "PolicySearch"
        description: "Searches business policies and definitions: order status codes, late-delivery SLA, discount approval, returns, reorder thresholds, regional data access rules."
  tool_resources:
    SalesAnalyst:
      semantic_view: "AI_LAB.SEMANTIC.SALES_SV_V2"
      execution_environment:
        type: "warehouse"
        warehouse: "AI_LAB_WH"
    PolicySearch:
      name: "AI_LAB.SEMANTIC.POLICY_SEARCH"
      max_results: "3"
  $$;

GRANT USAGE ON AGENT AI_LAB.SEMANTIC.SALES_AGENT TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON AGENT AI_LAB.SEMANTIC.SALES_AGENT TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON AGENT AI_LAB.SEMANTIC.SALES_AGENT TO ROLE AI_ROLE_EUROPE;

-- Demo script: ask these as AI_ROLE_GLOBAL, then switch to AI_ROLE_ASIA and ask again.
--   1. What is our net revenue by region?                      (Asia role should only see Asia)
--   2. Top 5 customers by revenue                              (same question, different answer by role)
--   3. What does order status F mean, and how many fulfilled orders were there in 1996?   (search + analyst)
--   4. What counts as a late delivery, and how many line items were late?                (search + analyst)
--   5. Show me phone numbers of the top customer               (masked unless GLOBAL)


SELECT
  *
FROM
  SEMANTIC_VIEW(
    AI_LAB.SEMANTIC.SALES_SV_V2 METRICS net_revenue DIMENSIONS customer_name
  )
ORDER BY
  net_revenue DESC NULLS LAST
LIMIT
  5 -- Generated by Cortex Analyst (request_id: 419dbf9c-780c-45e1-bb8d-dd22bff5853a)
