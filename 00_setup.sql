-- =====================================================================
-- 00_setup.sql | Roles, warehouse, database, schemas, cost guardrails
-- Run once as ACCOUNTADMIN. All project objects are owned by SYSADMIN.
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- Only if Cortex models are not available in your account's region:
-- ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- Analyst roles: GLOBAL sees everything; ASIA / EUROPE see only their region
CREATE ROLE IF NOT EXISTS AI_ROLE_GLOBAL;
CREATE ROLE IF NOT EXISTS AI_ROLE_ASIA;
CREATE ROLE IF NOT EXISTS AI_ROLE_EUROPE;

-- SYSADMIN inherits them, so the object owner can still see all rows
GRANT ROLE AI_ROLE_GLOBAL TO ROLE SYSADMIN;
GRANT ROLE AI_ROLE_ASIA   TO ROLE SYSADMIN;
GRANT ROLE AI_ROLE_EUROPE TO ROLE SYSADMIN;

-- Let your own user switch between the roles (for testing)
SET my_user = CURRENT_USER();
GRANT ROLE AI_ROLE_GLOBAL TO USER IDENTIFIER($my_user);
GRANT ROLE AI_ROLE_ASIA   TO USER IDENTIFIER($my_user);
GRANT ROLE AI_ROLE_EUROPE TO USER IDENTIFIER($my_user);

-- Cortex access
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER        TO ROLE AI_ROLE_GLOBAL;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER        TO ROLE AI_ROLE_ASIA;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER        TO ROLE AI_ROLE_EUROPE;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER  TO ROLE AI_ROLE_GLOBAL;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER  TO ROLE AI_ROLE_ASIA;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER  TO ROLE AI_ROLE_EUROPE;

-- Objects
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS AI_LAB_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS AI_LAB;
CREATE SCHEMA IF NOT EXISTS AI_LAB.BRONZE;
CREATE SCHEMA IF NOT EXISTS AI_LAB.SILVER;
CREATE SCHEMA IF NOT EXISTS AI_LAB.GOLD;
CREATE SCHEMA IF NOT EXISTS AI_LAB.GOVERNANCE;
CREATE SCHEMA IF NOT EXISTS AI_LAB.SEMANTIC;
CREATE SCHEMA IF NOT EXISTS AI_LAB.DOCS;

-- Cost guardrail (note: covers warehouse credits, not Cortex AI-service credits)
USE ROLE ACCOUNTADMIN;
CREATE OR REPLACE RESOURCE MONITOR AI_LAB_RM WITH CREDIT_QUOTA = 20
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE AI_LAB_WH SET RESOURCE_MONITOR = AI_LAB_RM;

-- Access for analyst roles
USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE AI_LAB_WH TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON WAREHOUSE AI_LAB_WH TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON WAREHOUSE AI_LAB_WH TO ROLE AI_ROLE_EUROPE;

GRANT USAGE ON DATABASE AI_LAB TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON DATABASE AI_LAB TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON DATABASE AI_LAB TO ROLE AI_ROLE_EUROPE;

GRANT USAGE ON SCHEMA AI_LAB.GOLD     TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON SCHEMA AI_LAB.GOLD     TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON SCHEMA AI_LAB.GOLD     TO ROLE AI_ROLE_EUROPE;
GRANT USAGE ON SCHEMA AI_LAB.SEMANTIC TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON SCHEMA AI_LAB.SEMANTIC TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON SCHEMA AI_LAB.SEMANTIC TO ROLE AI_ROLE_EUROPE;
GRANT USAGE ON SCHEMA AI_LAB.DOCS     TO ROLE AI_ROLE_GLOBAL;
GRANT USAGE ON SCHEMA AI_LAB.DOCS     TO ROLE AI_ROLE_ASIA;
GRANT USAGE ON SCHEMA AI_LAB.DOCS     TO ROLE AI_ROLE_EUROPE;

-- Future grants: Gold tables are re-created by CREATE OR REPLACE, so grant on FUTURE objects
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA AI_LAB.GOLD TO ROLE AI_ROLE_GLOBAL;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA AI_LAB.GOLD TO ROLE AI_ROLE_ASIA;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA AI_LAB.GOLD TO ROLE AI_ROLE_EUROPE;