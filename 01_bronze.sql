-- =====================================================================
-- 01_bronze.sql | Raw landing layer (1:1 copy of source + audit columns)
-- Source: SNOWFLAKE_SAMPLE_DATA.TPCH_SF1 (an ERP-style orders / parts /
-- suppliers dataset available in every account). In a real project this
-- layer is fed by Snowpipe / Openflow / COPY INTO from files or CDC.
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE AI_LAB_WH;
USE SCHEMA AI_LAB.BRONZE;

CREATE OR REPLACE TABLE RAW_REGION   AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION;
CREATE OR REPLACE TABLE RAW_NATION   AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION;
CREATE OR REPLACE TABLE RAW_CUSTOMER AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER;
CREATE OR REPLACE TABLE RAW_SUPPLIER AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER;
CREATE OR REPLACE TABLE RAW_PART     AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART;
CREATE OR REPLACE TABLE RAW_PARTSUPP AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP;
CREATE OR REPLACE TABLE RAW_ORDERS   AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS;
CREATE OR REPLACE TABLE RAW_LINEITEM AS SELECT *, CURRENT_TIMESTAMP() AS _LOADED_AT, 'TPCH_SF1' AS _SOURCE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM;

-- Sanity check
SELECT 'RAW_ORDERS' AS tbl, COUNT(*) AS row_count FROM RAW_ORDERS
UNION ALL SELECT 'RAW_LINEITEM', COUNT(*) FROM RAW_LINEITEM
UNION ALL SELECT 'RAW_CUSTOMER', COUNT(*) FROM RAW_CUSTOMER;

alter warehouse AI_LAB_WH resume;

select * from RAW_REGION;
select * from RAW_NATION;
select * from RAW_CUSTOMER;
select * from RAW_SUPPLIER;
select * from RAW_PART;
select * from RAW_PARTSUPP;
select * from RAW_ORDERS;
select * from RAW_LINEITEM;