-- =====================================================================
-- 03_gold.sql | Business-ready star schema (Dynamic Tables)
-- Facts are built from SILVER (not from other Gold tables) so that row
-- access policies on Gold never affect downstream refreshes.
-- Every table that needs regional security carries REGION_NAME.
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE AI_LAB_WH;
USE SCHEMA AI_LAB.GOLD;

CREATE OR REPLACE DYNAMIC TABLE DIM_CUSTOMER
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT c.CUSTOMER_KEY, c.CUSTOMER_NAME, c.MARKET_SEGMENT,
       nr.NATION_NAME, nr.REGION_NAME, c.PHONE, c.ACCOUNT_BALANCE
FROM AI_LAB.SILVER.CUSTOMERS c
JOIN AI_LAB.SILVER.NATIONS_REGIONS nr ON c.NATION_KEY = nr.NATION_KEY;

CREATE OR REPLACE DYNAMIC TABLE DIM_SUPPLIER
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT s.SUPPLIER_KEY, s.SUPPLIER_NAME, nr.NATION_NAME, nr.REGION_NAME
FROM AI_LAB.SILVER.SUPPLIERS s
JOIN AI_LAB.SILVER.NATIONS_REGIONS nr ON s.NATION_KEY = nr.NATION_KEY;

CREATE OR REPLACE DYNAMIC TABLE DIM_PART
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT PART_KEY, PART_NAME, MANUFACTURER, BRAND, PART_TYPE, PART_SIZE, CONTAINER, RETAIL_PRICE
FROM AI_LAB.SILVER.PARTS;

CREATE OR REPLACE DYNAMIC TABLE FCT_ORDERS
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT o.ORDER_KEY, o.CUSTOMER_KEY, nr.REGION_NAME,
       o.ORDER_DATE, YEAR(o.ORDER_DATE) AS ORDER_YEAR,
       o.ORDER_STATUS, o.ORDER_PRIORITY, o.TOTAL_PRICE
FROM AI_LAB.SILVER.ORDERS o
JOIN AI_LAB.SILVER.CUSTOMERS c        ON o.CUSTOMER_KEY = c.CUSTOMER_KEY
JOIN AI_LAB.SILVER.NATIONS_REGIONS nr ON c.NATION_KEY   = nr.NATION_KEY;

CREATE OR REPLACE DYNAMIC TABLE FCT_ORDER_LINES
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT l.ORDER_KEY, l.LINE_NUMBER, l.PART_KEY, l.SUPPLIER_KEY,
       nr.REGION_NAME,                       -- customer's region
       l.QUANTITY, l.NET_AMOUNT, l.SHIP_MODE, l.RETURN_FLAG, l.IS_LATE_DELIVERY
FROM AI_LAB.SILVER.ORDER_LINES l
JOIN AI_LAB.SILVER.ORDERS o           ON l.ORDER_KEY    = o.ORDER_KEY
JOIN AI_LAB.SILVER.CUSTOMERS c        ON o.CUSTOMER_KEY = c.CUSTOMER_KEY
JOIN AI_LAB.SILVER.NATIONS_REGIONS nr ON c.NATION_KEY   = nr.NATION_KEY;

CREATE OR REPLACE DYNAMIC TABLE FCT_INVENTORY
  TARGET_LAG = '1 hour' WAREHOUSE = AI_LAB_WH
AS
SELECT ps.PART_KEY, ps.SUPPLIER_KEY,
       nr.REGION_NAME,                       -- supplier's region
       ps.AVAILABLE_QTY, ps.SUPPLY_COST,
       ps.AVAILABLE_QTY * ps.SUPPLY_COST AS INVENTORY_VALUE
FROM AI_LAB.SILVER.PART_SUPPLY ps
JOIN AI_LAB.SILVER.SUPPLIERS s        ON ps.SUPPLIER_KEY = s.SUPPLIER_KEY
JOIN AI_LAB.SILVER.NATIONS_REGIONS nr ON s.NATION_KEY    = nr.NATION_KEY;

-- Sanity check
SELECT REGION_NAME, COUNT(*) AS orders FROM FCT_ORDERS GROUP BY 1 ORDER BY 1;