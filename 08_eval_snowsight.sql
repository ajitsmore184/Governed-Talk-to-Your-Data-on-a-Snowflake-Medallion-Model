-- Compares result sets in both directions (MINUS). Column COUNT and ORDER must
-- match the expected SQL; if Analyst returns extra columns, use the manual
-- override at the bottom of this file.
CREATE OR REPLACE PROCEDURE AI_LAB.GOVERNANCE.RECORD_RESULT(P_Q_ID NUMBER, P_LABEL STRING, P_GENERATED_SQL STRING)
RETURNS STRING
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
  v_expected  STRING;
  v_generated STRING;
  v_missing   NUMBER DEFAULT 0;
  v_extra     NUMBER DEFAULT 0;
  v_status    STRING DEFAULT 'FAIL';
BEGIN
  SELECT EXPECTED_SQL INTO :v_expected FROM AI_LAB.GOVERNANCE.EVAL_QUESTIONS WHERE Q_ID = :P_Q_ID;
  v_expected  := RTRIM(:v_expected,       '; ' || CHR(10) || CHR(9) || CHR(13));
  v_generated := RTRIM(:P_GENERATED_SQL,  '; ' || CHR(10) || CHR(9) || CHR(13));

  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ((' || v_expected || CHR(10) || ') MINUS (' || v_generated || CHR(10) || '))';
  SELECT $1 INTO :v_missing FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM ((' || v_generated || CHR(10) || ') MINUS (' || v_expected || CHR(10) || '))';
  SELECT $1 INTO :v_extra FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  IF (v_missing = 0 AND v_extra = 0) THEN
    v_status := 'PASS';
  END IF;

  DELETE FROM AI_LAB.GOVERNANCE.EVAL_RESULTS WHERE Q_ID = :P_Q_ID AND VIEW_LABEL = :P_LABEL;
  INSERT INTO AI_LAB.GOVERNANCE.EVAL_RESULTS VALUES (:P_Q_ID, :P_LABEL, :v_status, :P_GENERATED_SQL, CURRENT_TIMESTAMP());
  RETURN v_status || ' (rows missing: ' || v_missing || ', unexpected rows: ' || v_extra || ')';
EXCEPTION
  WHEN OTHER THEN
    DELETE FROM AI_LAB.GOVERNANCE.EVAL_RESULTS WHERE Q_ID = :P_Q_ID AND VIEW_LABEL = :P_LABEL;
    INSERT INTO AI_LAB.GOVERNANCE.EVAL_RESULTS VALUES (:P_Q_ID, :P_LABEL, 'ERROR', :P_GENERATED_SQL, CURRENT_TIMESTAMP());
    RETURN 'ERROR: ' || SQLERRM;
END;
$$;

