USE ROLE SYSADMIN;
USE WAREHOUSE AI_LAB_WH;
USE SCHEMA AI_LAB.SILVER;

alter warehouse AI_LAB_WH resume;

CREATE OR REPLACE DYNAMIC TABLE NATIONS_REGIONS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT n.N_NATIONKEY        AS NATION_KEY,
       INITCAP(n.N_NAME)    AS NATION_NAME,
       INITCAP(r.R_NAME)    AS REGION_NAME      -- Africa, America, Asia, Europe, Middle East
FROM AI_LAB.BRONZE.RAW_NATION n
JOIN AI_LAB.BRONZE.RAW_REGION r ON n.N_REGIONKEY = r.R_REGIONKEY;

CREATE OR REPLACE DYNAMIC TABLE CUSTOMERS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT C_CUSTKEY AS CUSTOMER_KEY, TRIM(C_NAME) AS CUSTOMER_NAME, C_NATIONKEY AS NATION_KEY,
       C_PHONE AS PHONE, C_ACCTBAL AS ACCOUNT_BALANCE, C_MKTSEGMENT AS MARKET_SEGMENT
FROM AI_LAB.BRONZE.RAW_CUSTOMER
WHERE C_CUSTKEY IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE SUPPLIERS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT S_SUPPKEY AS SUPPLIER_KEY, TRIM(S_NAME) AS SUPPLIER_NAME, S_NATIONKEY AS NATION_KEY
FROM AI_LAB.BRONZE.RAW_SUPPLIER
WHERE S_SUPPKEY IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE PARTS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT P_PARTKEY AS PART_KEY, P_NAME AS PART_NAME, P_MFGR AS MANUFACTURER, P_BRAND AS BRAND,
       P_TYPE AS PART_TYPE, P_SIZE AS PART_SIZE, P_CONTAINER AS CONTAINER, P_RETAILPRICE AS RETAIL_PRICE
FROM AI_LAB.BRONZE.RAW_PART
WHERE P_PARTKEY IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE PART_SUPPLY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT PS_PARTKEY AS PART_KEY, PS_SUPPKEY AS SUPPLIER_KEY,
       PS_AVAILQTY AS AVAILABLE_QTY, PS_SUPPLYCOST AS SUPPLY_COST
FROM AI_LAB.BRONZE.RAW_PARTSUPP;

CREATE OR REPLACE DYNAMIC TABLE ORDERS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT O_ORDERKEY AS ORDER_KEY, O_CUSTKEY AS CUSTOMER_KEY, O_ORDERSTATUS AS ORDER_STATUS,
       O_TOTALPRICE AS TOTAL_PRICE, O_ORDERDATE AS ORDER_DATE, O_ORDERPRIORITY AS ORDER_PRIORITY
FROM AI_LAB.BRONZE.RAW_ORDERS
WHERE O_ORDERKEY IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE ORDER_LINES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AI_LAB_WH
AS
SELECT L_ORDERKEY AS ORDER_KEY, L_LINENUMBER AS LINE_NUMBER, L_PARTKEY AS PART_KEY, L_SUPPKEY AS SUPPLIER_KEY,
       L_QUANTITY AS QUANTITY,
       ROUND(L_EXTENDEDPRICE * (1 - L_DISCOUNT), 2) AS NET_AMOUNT,
       L_RETURNFLAG AS RETURN_FLAG, L_SHIPMODE AS SHIP_MODE,
       (L_RECEIPTDATE > L_COMMITDATE) AS IS_LATE_DELIVERY
FROM AI_LAB.BRONZE.RAW_LINEITEM;