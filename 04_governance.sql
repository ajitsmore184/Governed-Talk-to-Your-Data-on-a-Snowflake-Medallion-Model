-- =====================================================================
-- 04_governance.sql | Row access + masking policies, then prove them
-- Rule: GLOBAL sees all rows and real phone numbers.
--       ASIA / EUROPE see only their own region and masked phone numbers.
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE AI_LAB_WH;
USE SCHEMA AI_LAB.GOVERNANCE;

CREATE OR REPLACE TABLE ROLE_REGION_MAP (ROLE_NAME STRING, REGION_NAME STRING);
INSERT INTO ROLE_REGION_MAP VALUES ('AI_ROLE_ASIA', 'Asia'), ('AI_ROLE_EUROPE', 'Europe');

-- NOTE: the policy argument is named P_REGION (not REGION_NAME) so it is not
-- confused with the mapping table's REGION_NAME column inside the subquery.
CREATE OR REPLACE ROW ACCESS POLICY RAP_REGION AS (P_REGION STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('AI_ROLE_GLOBAL')
  OR EXISTS (
       SELECT 1 FROM AI_LAB.GOVERNANCE.ROLE_REGION_MAP m
       WHERE m.ROLE_NAME = CURRENT_ROLE() AND m.REGION_NAME = P_REGION
     );

CREATE OR REPLACE MASKING POLICY MASK_PHONE AS (VAL STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('AI_ROLE_GLOBAL') THEN VAL
       ELSE CONCAT('XXX-XXX-', RIGHT(VAL, 4)) END;

-- Attach policies to the Gold tables
ALTER DYNAMIC TABLE AI_LAB.GOLD.DIM_CUSTOMER    ADD ROW ACCESS POLICY AI_LAB.GOVERNANCE.RAP_REGION ON (REGION_NAME);
ALTER DYNAMIC TABLE AI_LAB.GOLD.DIM_SUPPLIER    ADD ROW ACCESS POLICY AI_LAB.GOVERNANCE.RAP_REGION ON (REGION_NAME);
ALTER DYNAMIC TABLE AI_LAB.GOLD.FCT_ORDERS      ADD ROW ACCESS POLICY AI_LAB.GOVERNANCE.RAP_REGION ON (REGION_NAME);
ALTER DYNAMIC TABLE AI_LAB.GOLD.FCT_ORDER_LINES ADD ROW ACCESS POLICY AI_LAB.GOVERNANCE.RAP_REGION ON (REGION_NAME);
ALTER DYNAMIC TABLE AI_LAB.GOLD.FCT_INVENTORY   ADD ROW ACCESS POLICY AI_LAB.GOVERNANCE.RAP_REGION ON (REGION_NAME);

ALTER DYNAMIC TABLE AI_LAB.GOLD.DIM_CUSTOMER MODIFY COLUMN PHONE SET MASKING POLICY AI_LAB.GOVERNANCE.MASK_PHONE;

-- ---------- PROVE IT (screenshot these for your README) ----------
USE ROLE AI_ROLE_GLOBAL;  USE WAREHOUSE AI_LAB_WH;
SELECT REGION_NAME, COUNT(*) AS orders FROM AI_LAB.GOLD.FCT_ORDERS GROUP BY 1 ORDER BY 1;   -- 5 regions
SELECT CUSTOMER_NAME, PHONE FROM AI_LAB.GOLD.DIM_CUSTOMER LIMIT 3;                          -- real phones

USE ROLE AI_ROLE_ASIA;    USE WAREHOUSE AI_LAB_WH;
SELECT REGION_NAME, COUNT(*) AS orders FROM AI_LAB.GOLD.FCT_ORDERS GROUP BY 1 ORDER BY 1;   -- only Asia
SELECT CUSTOMER_NAME, PHONE,REGION_NAME FROM AI_LAB.GOLD.DIM_CUSTOMER LIMIT 3;                          -- masked phones

USE ROLE AI_ROLE_EUROPE;  USE WAREHOUSE AI_LAB_WH;
SELECT REGION_NAME, COUNT(*) AS orders FROM AI_LAB.GOLD.FCT_ORDERS GROUP BY 1 ORDER BY 1;   -- only Europe

USE ROLE SYSADMIN;

